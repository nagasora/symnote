-- SymNote PostgreSQL data schema, snapshot version 18.
-- All date/time values remain TEXT to preserve the local SQLite data contract.

CREATE TABLE IF NOT EXISTS task_recurrence_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  frequency TEXT NOT NULL CHECK(frequency IN ('daily', 'weekly', 'weekdays', 'monthly', 'custom')),
  interval_days INTEGER NOT NULL CHECK(interval_days > 0),
  end_date TEXT,
  active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0, 1)),
  created_at TEXT NOT NULL,
  weekdays TEXT NOT NULL DEFAULT '',
  month_day INTEGER CHECK(month_day BETWEEN 1 AND 31)
);

CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT,
  date TEXT,
  due_date TEXT,
  due_time TEXT,
  kind TEXT,
  raw_text TEXT,
  ai_category TEXT,
  importance INTEGER,
  urgency INTEGER,
  effort TEXT,
  energy TEXT,
  status TEXT,
  tags TEXT,
  embedding BYTEA,
  recurrence_rule_id BIGINT,
  goal_id BIGINT,
  estimate_minutes INTEGER,
  completed_at TEXT,
  delegated_to TEXT
);

CREATE TABLE IF NOT EXISTS calendar_task_sync (
  task_id BIGINT PRIMARY KEY,
  event_id TEXT,
  last_synced_at TEXT,
  calendar_id TEXT,
  content_hash TEXT
);

CREATE TABLE IF NOT EXISTS calendar_sync_outbox (
  task_id BIGINT PRIMARY KEY,
  operation TEXT NOT NULL CHECK(operation IN ('upsert', 'delete')),
  changed_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS calendar_morning_digest_sync (
  digest_date TEXT PRIMARY KEY,
  event_id TEXT NOT NULL,
  content_hash TEXT NOT NULL,
  last_synced_at TEXT NOT NULL,
  calendar_id TEXT
);

CREATE TABLE IF NOT EXISTS task_candidates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  source TEXT NOT NULL,
  source_ref TEXT NOT NULL,
  source_url TEXT,
  title TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  excerpt TEXT NOT NULL DEFAULT '',
  due_date TEXT,
  due_time TEXT,
  confidence DOUBLE PRECISION,
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending', 'approved', 'rejected')),
  decided_at TEXT,
  task_id BIGINT,
  UNIQUE(source, source_ref, title)
);

CREATE TABLE IF NOT EXISTS oauth_clients (
  client_id TEXT PRIMARY KEY,
  client_info TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS oauth_tokens (
  token_hash TEXT PRIMARY KEY,
  kind TEXT NOT NULL CHECK(kind IN ('access', 'refresh')),
  client_id TEXT NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE
    DEFERRABLE INITIALLY IMMEDIATE,
  scopes TEXT NOT NULL DEFAULT '',
  resource TEXT,
  expires_at BIGINT NOT NULL,
  created_at TEXT NOT NULL,
  consumed_at BIGINT
);

CREATE TABLE IF NOT EXISTS calendar_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS calendar_event_cache (
  calendar_id TEXT NOT NULL,
  range_start TEXT NOT NULL,
  range_end TEXT NOT NULL,
  fetched_at TEXT NOT NULL,
  payload TEXT NOT NULL,
  PRIMARY KEY(calendar_id, range_start, range_end)
);

CREATE TABLE IF NOT EXISTS goals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT REFERENCES goals(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  title TEXT NOT NULL,
  why TEXT NOT NULL DEFAULT '',
  success_criteria TEXT NOT NULL DEFAULT '',
  target_date TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active', 'done', 'archived')),
  order_index INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS quest_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  xp INTEGER NOT NULL CHECK(xp >= 0),
  gold INTEGER NOT NULL CHECK(gold >= 0),
  bonus TEXT NOT NULL DEFAULT '',
  completed_at TEXT NOT NULL,
  seen INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS quest_bonus_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK(kind IN ('daily_clear', 'triage')),
  ref TEXT NOT NULL,
  xp INTEGER NOT NULL CHECK(xp >= 0),
  gold INTEGER NOT NULL CHECK(gold >= 0),
  created_at TEXT NOT NULL,
  seen INTEGER NOT NULL DEFAULT 0,
  UNIQUE(kind, ref)
);

CREATE TABLE IF NOT EXISTS rewards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  cost INTEGER NOT NULL CHECK(cost > 0),
  icon TEXT NOT NULL DEFAULT '🎁',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reward_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reward_id BIGINT NOT NULL REFERENCES rewards(id) DEFERRABLE INITIALLY IMMEDIATE,
  title TEXT NOT NULL,
  cost INTEGER NOT NULL CHECK(cost > 0),
  redeemed_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS achievements (
  code TEXT PRIMARY KEY,
  unlocked_at TEXT NOT NULL,
  seen INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS app_settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS secretary_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK(role IN ('user', 'secretary')),
  content TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS time_blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day TEXT NOT NULL,
  task_id BIGINT,
  title TEXT NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'planned' CHECK(status IN ('planned', 'exported', 'cancelled')),
  calendar_event_id TEXT,
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS focus_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT,
  title TEXT NOT NULL,
  planned_minutes INTEGER NOT NULL CHECK(planned_minutes > 0),
  started_at TEXT NOT NULL,
  ended_at TEXT,
  outcome TEXT CHECK(outcome IN ('done', 'stopped')),
  bonus_xp INTEGER NOT NULL DEFAULT 0 CHECK(bonus_xp >= 0),
  bonus_gold INTEGER NOT NULL DEFAULT 0 CHECK(bonus_gold >= 0)
);

CREATE TABLE IF NOT EXISTS agent_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT,
  goal_id BIGINT,
  agent TEXT NOT NULL DEFAULT '',
  summary TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  suggested_status TEXT NOT NULL DEFAULT 'progress'
    CHECK(suggested_status IN ('progress', 'done', 'blocked')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending', 'approved', 'rejected')),
  created_at TEXT NOT NULL,
  reviewed_at TEXT
);

CREATE TABLE IF NOT EXISTS idea_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT,
  summary TEXT,
  source_text TEXT,
  chat_history TEXT,
  created_at TEXT,
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS mindmap_nodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  parent_id BIGINT,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT,
  order_index INTEGER DEFAULT 0,
  depth INTEGER DEFAULT 0,
  linked_item_id BIGINT,
  created_at TEXT,
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS gmail_import_processed (
  source_ref TEXT PRIMARY KEY,
  processed_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_items_date ON items(date);
CREATE INDEX IF NOT EXISTS idx_items_due_date ON items(due_date);
CREATE INDEX IF NOT EXISTS idx_items_kind ON items(kind);
CREATE INDEX IF NOT EXISTS idx_items_status ON items(status);
CREATE INDEX IF NOT EXISTS idx_items_completed_at ON items(completed_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_recurrence_occurrence
  ON items(recurrence_rule_id, due_date) WHERE recurrence_rule_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_calendar_outbox_changed ON calendar_sync_outbox(changed_at);
CREATE INDEX IF NOT EXISTS idx_calendar_morning_digest_synced
  ON calendar_morning_digest_sync(last_synced_at);
CREATE INDEX IF NOT EXISTS idx_task_candidates_status ON task_candidates(status, created_at);
CREATE INDEX IF NOT EXISTS idx_oauth_tokens_client ON oauth_tokens(client_id, kind);
CREATE INDEX IF NOT EXISTS idx_goals_parent ON goals(parent_id);
CREATE INDEX IF NOT EXISTS idx_items_goal ON items(goal_id);
CREATE INDEX IF NOT EXISTS idx_quest_log_completed ON quest_log(completed_at);
CREATE INDEX IF NOT EXISTS idx_quest_bonus_created ON quest_bonus_log(created_at);
CREATE INDEX IF NOT EXISTS idx_time_blocks_day ON time_blocks(day);
CREATE INDEX IF NOT EXISTS idx_focus_sessions_started ON focus_sessions(started_at);
CREATE INDEX IF NOT EXISTS idx_agent_reports_status ON agent_reports(status);
CREATE INDEX IF NOT EXISTS idx_mindmap_project ON mindmap_nodes(project_id);
CREATE INDEX IF NOT EXISTS idx_mindmap_parent ON mindmap_nodes(parent_id);

CREATE TABLE IF NOT EXISTS source_connections (
  provider TEXT PRIMARY KEY,
  revision TEXT NOT NULL,
  credentials TEXT NOT NULL,
  account TEXT NOT NULL,
  workspace TEXT NOT NULL DEFAULT '',
  channels TEXT NOT NULL DEFAULT '[]',
  checkpoint TEXT NOT NULL DEFAULT '{}',
  verified_at DOUBLE PRECISION NOT NULL,
  last_fetch_at DOUBLE PRECISION,
  last_success_at DOUBLE PRECISION,
  last_error TEXT NOT NULL DEFAULT '',
  run_id TEXT NOT NULL DEFAULT '',
  run_until DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS source_oauth_states (
  state_hash TEXT PRIMARY KEY,
  provider TEXT NOT NULL,
  session_hash TEXT NOT NULL,
  expires_at DOUBLE PRECISION NOT NULL,
  consumed INTEGER NOT NULL DEFAULT 0,
  payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS source_processed (
  provider TEXT NOT NULL,
  source_ref TEXT NOT NULL,
  PRIMARY KEY (provider, source_ref)
);
